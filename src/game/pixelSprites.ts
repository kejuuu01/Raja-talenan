const spriteCache = new Map<string, HTMLCanvasElement>();
const sliceCache = new Map<string, HTMLCanvasElement>();

export function getIngredientSprite(id: string): HTMLCanvasElement {
  const cached = spriteCache.get(id);
  if (cached) return cached;

  const def = SPRITE_GRIDS[id] ?? SPRITE_GRIDS.wortel;
  const canvas = document.createElement('canvas');
  canvas.width = 16;
  canvas.height = 16;
  const ctx = canvas.getContext('2d')!;

  for (let y = 0; y < def.rows.length; y++) {
    const row = def.rows[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.' || !def.palette[ch]) continue;
      ctx.fillStyle = def.palette[ch];
      ctx.fillRect(x, y, 1, 1);
    }
  }

  spriteCache.set(id, canvas);
  return canvas;
}

export function getSliceSprite(id: string, mainColor: string, innerColor: string, seedColor?: string): HTMLCanvasElement {
  const key = `${id}_${mainColor}`;
  const cached = sliceCache.get(key);
  if (cached) return cached;

  const canvas = document.createElement('canvas');
  canvas.width = 10;
  canvas.height = 10;
  const ctx = canvas.getContext('2d')!;

  // Crisp pixel cross-section disc
  const disc = [
    '..OOOOOO..',
    '.OMMMMMMO.',
    'OMMIIIIMMO',
    'OMISIISIMO',
    'OMIIIIIIMO',
    'OMIISIIIMO',
    'OMMIIIIMMO',
    '.OMMMMMMO.',
    '..OOOOOO..',
    '..........',
  ];

  for (let y = 0; y < 10; y++) {
    for (let x = 0; x < 10; x++) {
      const ch = disc[y][x];
      if (ch === '.') continue;
      if (ch === 'O') ctx.fillStyle = '#3B2314';
      else if (ch === 'M') ctx.fillStyle = mainColor;
      else if (ch === 'I') ctx.fillStyle = innerColor;
      else if (ch === 'S') ctx.fillStyle = seedColor ?? innerColor;
      ctx.fillRect(x, y, 1, 1);
    }
  }

  sliceCache.set(key, canvas);
  return canvas;
}


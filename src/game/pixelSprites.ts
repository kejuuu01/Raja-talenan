export function getKnifeSprite(knife: KnifeDef): HTMLCanvasElement {
  const cached = knifeCache.get(knife.id);
  if (cached) return cached;

  const canvas = document.createElement('canvas');
  canvas.width = 24;
  canvas.height = 12;
  const ctx = canvas.getContext('2d')!;

  const grid = KNIFE_GRIDS[knife.shape] ?? KNIFE_GRIDS.chef;
  const offsetY = Math.floor((12 - grid.length) / 2);

  for (let y = 0; y < grid.length; y++) {
    const row = grid[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      if (ch === 'O') ctx.fillStyle = '#3B2314';
      else if (ch === 'B') ctx.fillStyle = knife.bladeColor;
      else if (ch === 'E') ctx.fillStyle = knife.edgeColor;
      else if (ch === 'H') ctx.fillStyle = knife.handleColor;
      else if (ch === 'A') ctx.fillStyle = knife.accentColor;
      ctx.fillRect(x, y + offsetY, 1, 1);
    }
  }

  knifeCache.set(knife.id, canvas);
  return canvas;
}
